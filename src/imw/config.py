"""Project-wide constants and paths."""

from __future__ import annotations

import os
from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CONTRACTS_PATH = REPO_ROOT / "contracts" / "contracts.yml"
DBT_DIR = REPO_ROOT / "dbt"
DEFAULT_LANDING = REPO_ROOT / "data" / "landing"
DEFAULT_DB = REPO_ROOT / "warehouse" / "imw.duckdb"
REPORTS_DIR = REPO_ROOT / "reports"

SIM_START = date(2025, 1, 1)
SIM_END = date(2025, 8, 31)  # last simulated event day (inclusive)
# Ingestion "as of" moment: all arrivals up to this instant are loaded. Late events can arrive
# up to ~10 days after SIM_END, so the last monthly batch (September) covers them.
AS_OF = datetime(2025, 10, 1, 0, 0, 0)

EXPERIMENT_ID = "crm_reactivation_2025_07"
EXPERIMENT_START = date(2025, 7, 1)
EXPERIMENT_DAYS = 28

SYNTHETIC_LABEL = "SYNTHETIC DEMO DATA — generated by imw.generator, not real operator data"


def db_path() -> Path:
    return Path(os.environ.get("IMW_DUCKDB_PATH", str(DEFAULT_DB)))


@dataclass(frozen=True)
class GeneratorConfig:
    seed: int = 42
    n_players: int = 4000
    start: date = SIM_START
    end: date = SIM_END
    duplicate_rate: float = 0.004
    late_rate: float = 0.015
    invalid_rate: float = 0.0015
    lost_callback_rate: float = 0.0005
    double_credit_rate: float = 0.0002
